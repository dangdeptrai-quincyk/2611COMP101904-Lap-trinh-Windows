SELECT sv.MaSV, sv.HoTen, mh.TenMH, kq.Diem
FROM KETQUA kq JOIN SINHVIEN sv ON kq.MaSV = sv.MaSV JOIN MONHOC mh ON kq.MaMH = mh.MaMH
ORDER BY sv.MaSV, mh.TenMH;
SELECT sv.MaSV, sv.HoTen, ROUND(AVG(kq.Diem), 2) AS DiemTB
FROM SINHVIEN sv JOIN KETQUA kq ON sv.MaSV = kq.MaSV
GROUP BY sv.MaSV, sv.HoTen;
SELECT l.MaLop, l.TenLop, COUNT(sv.MaSV) AS SoSV
FROM LOP l LEFT JOIN SINHVIEN sv ON l.MaLop = sv.MaLop
GROUP BY l.MaLop, l.TenLop;
SELECT l.MaLop, l.TenLop, COUNT(*) AS SoSV
FROM LOP l JOIN SINHVIEN sv ON l.MaLop = sv.MaLop
GROUP BY l.MaLop, l.TenLop
HAVING COUNT(*) >= 2;
