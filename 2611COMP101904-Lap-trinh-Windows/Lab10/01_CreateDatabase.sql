GO
   IF DB_ID('EduManagerDB') IS NOT NULL
   BEGIN
       ALTER DATABASE EduManagerDB SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
       DROP DATABASE EduManagerDB;
   END
GO
CREATE DATABASE EduManagerDB;
GO
USE EduManagerDB;
GO
CREATE TABLE KHOA (
    MaKhoa  VARCHAR(10)   NOT NULL PRIMARY KEY,
    TenKhoa NVARCHAR(100) NOT NULL
);
GO
CREATE TABLE LOP (
    MaLop  VARCHAR(10)   NOT NULL PRIMARY KEY,
    TenLop NVARCHAR(100) NOT NULL,
    MaKhoa VARCHAR(10)   NOT NULL,
    CONSTRAINT FK_LOP_KHOA FOREIGN KEY (MaKhoa) REFERENCES KHOA(MaKhoa)
);
GO
CREATE TABLE SINHVIEN (
    MaSV     VARCHAR(10)   NOT NULL PRIMARY KEY,
    HoTen    NVARCHAR(100) NOT NULL,
    NgaySinh DATE          NULL,
    GioiTinh NVARCHAR(3)   NOT NULL,
    MaLop    VARCHAR(10)   NOT NULL,
    CONSTRAINT CK_SINHVIEN_GioiTinh CHECK (GioiTinh IN (N'Nam', N'Nữ')),
    CONSTRAINT FK_SINHVIEN_LOP FOREIGN KEY (MaLop) REFERENCES LOP(MaLop)
);
GO
CREATE TABLE MONHOC (
    MaMH   VARCHAR(10)   NOT NULL PRIMARY KEY,
    TenMH  NVARCHAR(100) NOT NULL,
    SoTinChi INT         NOT NULL,
    CONSTRAINT CK_MONHOC_SoTinChi CHECK (SoTinChi > 0)
);
GO
CREATE TABLE KETQUA (
    MaSV VARCHAR(10) NOT NULL,
    MaMH VARCHAR(10) NOT NULL,
    Diem FLOAT       NOT NULL,
    CONSTRAINT PK_KETQUA PRIMARY KEY (MaSV, MaMH),
    CONSTRAINT FK_KETQUA_SV FOREIGN KEY (MaSV) REFERENCES SINHVIEN(MaSV),
    CONSTRAINT FK_KETQUA_MH FOREIGN KEY (MaMH) REFERENCES MONHOC(MaMH),
    CONSTRAINT CK_KETQUA_Diem CHECK (Diem BETWEEN 0 AND 10)
);
GO
CREATE TABLE TAIKHOAN (
    TenDangNhap VARCHAR(50)   NOT NULL PRIMARY KEY,
    MatKhau     VARCHAR(100)  NOT NULL,
    VaiTro      NVARCHAR(20)  NOT NULL DEFAULT N'User'
);
GO